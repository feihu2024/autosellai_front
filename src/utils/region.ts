/** 获取某省下辖的市列表 */
export function cityListOf(province: string): string[] {
  if (!province) return []
  const cities = regionData[province]
  return cities ? Object.keys(cities) : []
}

/** 获取某省某市下辖的区/县列表 */
export function districtListOf(province: string, city: string): string[] {
  if (!province || !city) return []
  const cities = regionData[province]
  if (!cities) return []
  return cities[city] || []
}
